import { useCallback, useEffect, useRef, useState } from "react";
import { summarizeCluster } from "../api/routing";
import { errorText, SectionHead } from "./ui";
import { fmtDate, human } from "../lib/format";
import type { ClusterAIStatement, ClusterSummary } from "../api/types";

/** "criteria.min_alerts" -> "Min Alerts": the cluster-data field a statement cites. */
const fieldLabel = (f: string) => human(f.split(".").pop() ?? f);

function Fields({ fields }: { fields: string[] }) {
  // Two fields can share a readable name (rules in the cluster and in the criteria); show it once.
  const labels = [...new Set(fields.map(fieldLabel))];
  if (!labels.length) return null;
  return (
    <span className="cites">
      {labels.map((l) => (
        <span key={l} className="cite cite-cl" title={`Cluster data: ${fields.filter((f) => fieldLabel(f) === l).join(", ")}`}>
          {l}
        </span>
      ))}
    </span>
  );
}

function List({ title, items }: { title: string; items: ClusterAIStatement[] }) {
  if (!items.length) return null;
  return (
    <div className="ai-block">
      <h3>{title}</h3>
      <ul className="ai-list">
        {items.map((s, i) => (
          <li key={i}>
            <span>{s.text}</span> <Fields fields={s.fields} />
          </li>
        ))}
      </ul>
    </div>
  );
}

/**
 * AI Cluster Summary. Renders only what POST /clusters/summary returned: an
 * explanation of why the deterministic engine grouped these alerts. It never
 * carries a routing, outcome or decision, and its absence blocks nothing.
 */
export function ClusterSummaryCard({ alertIds, n }: { alertIds: string[]; n: number }) {
  const [phase, setPhase] = useState<"running" | "done" | "failed">("running");
  const [result, setResult] = useState<ClusterSummary | null>(null);
  const [error, setError] = useState<unknown>(null);
  const run = useRef(0);
  const key = alertIds.join("|");

  const load = useCallback(async (regenerate = false) => {
    const token = ++run.current;
    setPhase("running");
    setError(null);
    try {
      const r = await summarizeCluster(alertIds, regenerate);
      if (run.current !== token) return;
      setResult(r);
      setPhase(r?.ai_summary ? "done" : "failed");
    } catch (e) {
      if (run.current !== token) return;
      setError(e);
      setPhase("failed");
    }
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [key]);

  useEffect(() => {
    void load();
  }, [load]);

  const s = result?.ai_summary;
  const generated = phase === "done" && s?.status === "generated";
  const unavailable = phase === "failed" || (phase === "done" && s && s.status !== "generated");

  return (
    <section className="card sec sec-ai" aria-label="AI Cluster Summary">
      <SectionHead n={n} tone="ai" title="AI Cluster Summary" right={<span className="pill pill-ai">AI-generated</span>} />
      <p className="ai-sub">
        AI-generated from the deterministic cluster result above. It explains why these alerts were grouped and decides
        nothing. <strong>A cluster is a grouping, not a finding; the analyst decides where it goes.</strong>
      </p>
      {phase === "running" ? (
        <div className="ai-state" role="status">
          <span className="spin" aria-hidden="true" /> Generating the summary from the cluster result…
        </div>
      ) : null}
      {unavailable ? (
        <div className="ai-off" role="status">
          <strong>AI summary unavailable</strong>
          <span>{phase === "failed" ? errorText(error).title : s?.reason}</span>
          <span>The deterministic detection criteria above are unaffected.</span>
        </div>
      ) : null}
      {generated && s ? (
        <div className="ai-body">
          <p className="ai-summary">
            {s.summary} <Fields fields={s.summary_fields} />
          </p>
          <div className="ai-grid">
            <List title="Criteria met" items={s.criteria_met} />
            <List title="Characteristics" items={s.characteristics} />
          </div>
          <div className="fine">
            Generated by {s.model}
            {s.generated_at ? ` on ${fmtDate(s.generated_at)}` : ""}
            {s.cached ? " · reused from the cache, no new model call" : ""}. Every statement names the cluster data it
            relies on.
          </div>
        </div>
      ) : null}
      {phase !== "running" ? (
        <div>
          <button className="btn btn-sm" onClick={() => void load(true)}>
            Regenerate AI summary
          </button>
        </div>
      ) : null}
    </section>
  );
}
