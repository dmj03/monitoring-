import { errorText, SectionHead } from "./ui";
import { fmtDate, fmtValue, human, toolLabel } from "../lib/format";
import type { AIStatement, InvestigationSummary } from "../api/types";

export type AiPhase = "waiting" | "running" | "done" | "failed";

/** Evidence keys a statement cites, as links to the evidence item below. */
function Cites({ keys }: { keys: string[] }) {
  if (!keys.length) return null;
  return (
    <span className="cites">
      {keys.map((k) => (
        <a key={k} className="cite" href={`#ev-${k}`} title={`Evidence: ${k}`}>
          {human(k)}
        </a>
      ))}
    </span>
  );
}

function Statements({ title, items, tone }: { title: string; items: AIStatement[]; tone?: string }) {
  if (!items.length) return null;
  return (
    <div className="ai-block">
      <h3>{title}</h3>
      <ul className={`ai-list ${tone ?? ""}`}>
        {items.map((s, i) => (
          <li key={i}>
            <span>{s.text}</span> <Cites keys={s.evidence_keys} />
          </li>
        ))}
      </ul>
    </div>
  );
}

/**
 * AI Analyst Summary. Renders only what POST /investigate/summary returned.
 * It explains the validated evidence pack; it never carries a decision,
 * outcome or confidence, and its absence never blocks the investigation.
 */
export function AISummaryCard({
  phase,
  result,
  error,
  onGenerate,
}: {
  phase: AiPhase;
  result: InvestigationSummary | null;
  error: unknown;
  onGenerate: () => void;
}) {
  const s = result?.ai_summary;
  const generated = phase === "done" && s?.status === "generated";
  const unavailable = phase === "failed" || (phase === "done" && s && s.status !== "generated");

  return (
    <section id="sec-ai" className="card sec sec-ai" aria-label="AI Analyst Summary">
      <SectionHead
        n={1}
        tone="ai"
        title="AI Analyst Summary"
        right={<span className="pill pill-ai">AI-generated</span>}
      />
      <p className="ai-sub">
        AI-generated from the validated investigation evidence in section 2. It explains that
        evidence and does not decide anything. <strong>The final decision remains with the analyst.</strong>
      </p>

      {phase === "waiting" ? (
        <div className="ai-state">Starts when the deterministic investigation has finished.</div>
      ) : null}

      {phase === "running" ? (
        <div className="ai-state" role="status">
          <span className="spin" aria-hidden="true" /> Generating the summary from the evidence pack…
        </div>
      ) : null}

      {unavailable ? (
        <div className="ai-off" role="status">
          <strong>AI summary unavailable</strong>
          <span>{phase === "failed" ? errorText(error).title : s?.reason}</span>
          <span>The deterministic investigation results are still available below.</span>
        </div>
      ) : null}

      {generated && s ? (
        <div className="ai-body">
          <p className="ai-summary">
            {s.summary} <Cites keys={s.summary_evidence_keys} />
          </p>
          {/* Missing items are named in the narrative itself (and listed in the
              evidence table), so they are not repeated as a separate block. */}
          <div className="ai-grid">
            <Statements title="Key findings" items={s.key_findings} />
            <Statements title="Analyst attention" items={s.analyst_attention} />
          </div>
          {s.evidence_basis.length ? (
            <details className="disclose">
              <summary>Evidence basis · {s.evidence_basis.length} cited items</summary>
              <table className="mini">
                <tbody>
                  {s.evidence_basis.map((e) => (
                    <tr key={e.key}>
                      <td>{human(e.key)}</td>
                      <td>
                        <span className={e.status === "MISSING" ? "st st-miss" : "st st-ok"}>{e.status}</span>
                      </td>
                      <td className="mono">{e.status === "MISSING" ? "Not available" : fmtValue(e.value)}</td>
                      <td className="dim">{toolLabel(e.tool)}</td>
                    </tr>
                  ))}
                </tbody>
              </table>
              <div className="fine">
                Copied from the investigation for every key the summary cites. Not model output.
              </div>
            </details>
          ) : null}
          <div className="fine">
            Generated by {s.model}
            {s.generated_at ? ` on ${fmtDate(s.generated_at)}` : ""}
            {s.cached ? " · reused from the cache, no new model call" : ""}. Every statement links to the evidence it
            cites.
          </div>
        </div>
      ) : null}

      {phase === "done" || phase === "failed" ? (
        <div>
          <button className="btn btn-sm" onClick={onGenerate}>
            Regenerate AI summary
          </button>
        </div>
      ) : null}
    </section>
  );
}
